// =============================================================================
// codegen.cpp  —  C Code Generator implementation for ResIR (Task 4)
// =============================================================================
//
// HOW "EMITTING" WORKS
// ─────────────────────
// Throughout this file you will see  out_ << "some text"
// Think of out_ as a blank sheet of paper.  Every << call writes another
// piece of text onto that paper, left to right, top to bottom.
// At the end, out_.str() gives us the complete .c source file as one string.
//
// We use std::ostringstream (declared in <sstream>) for this.
// It behaves exactly like std::cout but writes to memory instead of the screen.
//
// OVERALL STRUCTURE OF THE GENERATED FILE
// ─────────────────────────────────────────
//   #include <stdint.h>          ← fixed-width integer types (int32_t, …)
//   #include <stdbool.h>         ← bool, true, false in C
//   #include "resir_structs.h"   ← placeholder for user-defined struct headers
//
//   // forward struct declarations  (one per extern type in the ResIR program)
//
//   <return_type> <function_name>(<params>) {
//       // --- local variable declarations ---
//       <ctype> <name>;   (one per local)
//
//       goto <entry_label>;   (jump to the entry block)
//
//       <label>:              (one section per basic block)
//           <stmt1>;
//           <stmt2>;
//           <terminator>;     (goto / if+goto / return)
//   }
// =============================================================================

#include "codegen.hpp"
#include <fstream>    // std::ofstream — write to an actual file on disk
#include <stdexcept>  // std::runtime_error (not used directly, but good practice)
#include <algorithm>  // std::replace (for :: → _ conversion)

// =============================================================================
// Constructor
// =============================================================================
CodeGen::CodeGen(const Program& prog)
    : prog_(prog), fn_(prog.function)
{}

// =============================================================================
// emit() — run the whole generator; return the C source as a string
// =============================================================================
std::string CodeGen::emit() {
    // Clear any previous run (important if emit() is called twice).
    out_.str("");
    out_.clear();

    // Write the C file in top-to-bottom order:
    emit_headers();
    emit_extern_struct_decls();
    emit_function();

    return out_.str();
}

// =============================================================================
// emit_to_file() — emit() then write to disk
// =============================================================================
bool CodeGen::emit_to_file(const std::string& path) {
    std::string code = emit();
    std::ofstream f(path);
    if (!f.is_open()) return false;
    f << code;
    return true;
}

// =============================================================================
// emit_headers() — the mandatory #include lines every generated file needs
// =============================================================================
void CodeGen::emit_headers() {
    out_ << "// Generated by the ResIR compiler (Task 4)\n";
    out_ << "// Compile with:  gcc -std=c11 -Wall -Wextra -pedantic generated.c\n";
    out_ << "\n";

    // <stdint.h> gives us int32_t, int64_t, uint32_t  — portable fixed-width types.
    // Without it, "int" might be 16 bits on some platforms; "int32_t" is always 32.
    out_ << "#include <stdint.h>\n";

    // <stdbool.h> gives us the `bool` type and the constants `true` / `false`.
    // In C89/C90 there was no bool; in C11 it lives in this header.
    out_ << "#include <stdbool.h>\n";

    // A placeholder header for any user-defined struct types referenced via
    // extern type declarations.  In a real project this would be auto-generated
    // or provided by the user.
    out_ << "#include \"resir_structs.h\"\n";

    out_ << "\n";
}

// =============================================================================
// emit_extern_struct_decls() — forward-declare each extern type as a C struct
// =============================================================================
// WHY forward declarations?
//   When the generated function uses a pointer to a struct (e.g. Point*),
//   C needs to know that the struct exists even if its fields are defined
//   in the separate resir_structs.h.  A "struct Foo;" line tells the compiler
//   "Foo is a struct; I'll define it elsewhere."
void CodeGen::emit_extern_struct_decls() {
    if (prog_.extern_types.empty()) return;

    out_ << "// --- Forward declarations for extern types ---\n";
    for (const ExternType& et : prog_.extern_types) {
        // Convert  Custom::Struct::Point  →  Custom_Struct_Point
        std::string c_name = path_to_c(et.path);
        out_ << "typedef struct " << c_name << " " << c_name << ";\n";
    }
    out_ << "\n";
}

// =============================================================================
// emit_function() — emit the C function signature and body
// =============================================================================
void CodeGen::emit_function() {
    // -----------------------------------------------------------------------
    // 1. Return type
    // -----------------------------------------------------------------------
    // A void function has no return local — we emit "void".
    // A non-void function uses the declared return type.
    std::string ret_str;
    if (fn_.returns_void) {
        ret_str = "void";
    } else {
        ret_str = type_to_c(fn_.return_type);
    }

    // -----------------------------------------------------------------------
    // 2. Function name
    //    ResIR: Math::abs_diff   →   C: Math_abs_diff
    // -----------------------------------------------------------------------
    std::string fn_name = path_to_c(fn_.path);

    // -----------------------------------------------------------------------
    // 3. Parameter list
    //    ResIR: %a : i32, %b : i32   →   C: int32_t a, int32_t b
    // -----------------------------------------------------------------------
    std::string params_str;
    for (size_t i = 0; i < fn_.params.size(); ++i) {
        if (i > 0) params_str += ", ";
        // The parser already stripped the '%' when it stored param.name,
        // so param.name is already "a", "b", etc.
        params_str += type_to_c(fn_.params[i].type) + " " + fn_.params[i].name;
    }
    if (fn_.params.empty()) params_str = "void";

    // -----------------------------------------------------------------------
    // 4. Emit the signature line
    // -----------------------------------------------------------------------
    out_ << ret_str << " " << fn_name << "(" << params_str << ") {\n";

    // -----------------------------------------------------------------------
    // 5. Local variable declarations
    // -----------------------------------------------------------------------
    emit_locals();

    // -----------------------------------------------------------------------
    // 6. Jump to the entry block
    //    WHY: C does not execute code at a label unless control reaches it.
    //    We need an explicit "goto bb0" so execution starts at the right block.
    // -----------------------------------------------------------------------
    out_ << "\n";
    out_ << "    // Jump to the entry block of the function.\n";
    out_ << "    goto " << fn_.entry_label << ";\n";
    out_ << "\n";

    // -----------------------------------------------------------------------
    // 7. Emit each basic block in order
    // -----------------------------------------------------------------------
    for (const Block& blk : fn_.blocks) {
        emit_block(blk);
    }

    out_ << "}\n";
}

// =============================================================================
// emit_locals() — declare every ResIR local as a C variable
// =============================================================================
// WHY at the top of the function?
//   C99 and C11 allow declarations anywhere in a block, but ANSI C89 requires
//   all declarations before the first statement.  Because we're using
//   "goto" labels (which are technically "statements"), putting declarations
//   at the very top of the function body is the safest and most portable
//   approach.  It also mirrors how LLVM and other SSA-style IRs typically
//   lower locals to C: all up front, then all assignments.
void CodeGen::emit_locals() {
    if (fn_.locals.empty()) return;

    out_ << "    // --- Local variable declarations ---\n";
    out_ << "    // (All declared at the top to be compatible with C89 and\n";
    out_ << "    //  to avoid 'jump bypasses variable initialization' errors)\n";

    for (const LocalDecl& ld : fn_.locals) {
        // ld.name is already without '%' (the parser strips it).
        out_ << "    " << type_to_c(ld.type) << " " << ld.name << ";\n";
    }
}

// =============================================================================
// emit_block() — emit one basic block
// =============================================================================
// A basic block becomes:
//   label_name:               ← the C goto label
//       stmt1;
//       stmt2;
//       terminator;           ← goto / if+goto / return
//
// Note the leading semicolon trick:
//   In C, a label must be followed by a STATEMENT.  If a block had zero
//   statements and we put the label before the closing brace, GCC would
//   complain.  We avoid this by always emitting the terminator, which
//   counts as a statement.
void CodeGen::emit_block(const Block& blk) {
    // Emit the block label (C goto label syntax requires a colon suffix).
    out_ << "    " << blk.label << ":\n";

    // Emit each statement.
    for (const Statement& s : blk.stmts) {
        emit_stmt(s);
    }

    // Emit the terminator (jump / cjump / return).
    emit_terminator(blk.term);

    out_ << "\n";  // blank line between blocks for readability
}

// =============================================================================
// emit_stmt() — emit one statement as a C line
// =============================================================================
// There are two forms:
//   With destination:   int32_t d = a - b;
//   Without destination: *ptr = val;         (store has no dest)
void CodeGen::emit_stmt(const Statement& s) {
    if (s.rhs.kind == RhsKind::STORE) {
        // STORE has no destination variable.
        // It is:  store %ptr, %val  →  *ptr = val;
        // emit_rhs() for STORE returns the full assignment expression.
        out_ << "        " << emit_rhs(s.rhs) << ";\n";
        return;
    }

    if (s.has_dest) {
        // Normal assignment:  %dst = <rhs>  →  <ctype> dst = <c_rhs>;
        // The type comes from the locals table — we look it up.
        // (The validator already verified the type is correct, so we trust it.)
        //
        // We need the C type to declare the variable as part of the statement.
        // Wait — didn't we already declare all locals at the top?
        // YES.  So here we just emit the assignment without re-declaring.
        out_ << "        " << local_name(s.dest) << " = " << emit_rhs(s.rhs) << ";\n";
    } else {
        // Void call (CALL opcode with no destination).
        out_ << "        " << emit_rhs(s.rhs) << ";\n";
    }
}

// =============================================================================
// emit_rhs() — translate an Rhs opcode to a C expression string
// =============================================================================
// Returns a string like:
//   "a - b"           (BIN sub)
//   "Math_abs(x)"     (CALL)
//   "&p->field"       (MEMBER_PTR)
//   "*ptr"            (LOAD)
std::string CodeGen::emit_rhs(const Rhs& rhs) {
    switch (rhs.kind) {

    // -----------------------------------------------------------------------
    // COPY: %dst = %src  →  src
    // Just the name of the source local.
    // -----------------------------------------------------------------------
    case RhsKind::COPY:
        return local_name(rhs.op1);

    // -----------------------------------------------------------------------
    // CONST: %dst = const <literal>  →  42 / 3.14 / true / NULL
    // -----------------------------------------------------------------------
    case RhsKind::CONST: {
        const Literal& lit = rhs.literal;
        switch (lit.kind) {
            case LiteralKind::INT:
                // Use std::to_string to turn the integer into text.
                return std::to_string(lit.int_val);
            case LiteralKind::FLOAT: {
                // std::to_string for doubles sometimes produces trailing zeros.
                // That is fine for correctness; gcc will accept "3.140000".
                std::ostringstream ss;
                ss << lit.float_val;
                return ss.str();
            }
            case LiteralKind::BOOL:
                // "true" and "false" come from <stdbool.h>.
                return lit.bool_val ? "true" : "false";
            case LiteralKind::NULL_LIT:
                // NULL is the standard C null pointer constant.
                return "NULL";
        }
        return "0"; // unreachable
    }

    // -----------------------------------------------------------------------
    // CAST: %dst = cast %src to <type>  →  (ctype)src
    // An explicit C-style type cast.
    // -----------------------------------------------------------------------
    case RhsKind::CAST:
        return "(" + type_to_c(rhs.cast_type) + ")" + local_name(rhs.op1);

    // -----------------------------------------------------------------------
    // UN: %dst = un <op> %src  →  -src  /  !src
    // -----------------------------------------------------------------------
    case RhsKind::UN:
        return unop_str(rhs.un_op) + local_name(rhs.op1);

    // -----------------------------------------------------------------------
    // BIN: %dst = bin <op> %lhs, %rhs  →  lhs <op> rhs
    // -----------------------------------------------------------------------
    case RhsKind::BIN:
        return local_name(rhs.op1) + " " + binop_str(rhs.bin_op)
               + " " + local_name(rhs.op2);

    // -----------------------------------------------------------------------
    // ADDR_OF: %dst = addr_of %src  →  &src
    // Takes the address of a local variable.
    // -----------------------------------------------------------------------
    case RhsKind::ADDR_OF:
        return "&" + local_name(rhs.op1);

    // -----------------------------------------------------------------------
    // MEMBER_PTR: %dst = member_ptr %ptr, field  →  &ptr->field
    //
    // WHY &ptr->field?
    //   %ptr is already a pointer (ptr<Struct>).
    //   We want a POINTER to the field, not the field value itself.
    //   In C:  ptr->field  reads the field (type T).
    //          &ptr->field takes its address (type T*).
    //   That matches the ResIR semantics: member_ptr produces ptr<T>.
    // -----------------------------------------------------------------------
    case RhsKind::MEMBER_PTR:
        return "&" + local_name(rhs.op1) + "->" + rhs.field;

    // -----------------------------------------------------------------------
    // LOAD: %dst = load %ptr  →  *ptr
    //
    // Dereferences a pointer.  If %ptr : ptr<i32>, result is i32.
    // -----------------------------------------------------------------------
    case RhsKind::LOAD:
        return "*" + local_name(rhs.op1);

    // -----------------------------------------------------------------------
    // STORE: store %ptr, %val  →  *ptr = val
    //
    // Writes a value through a pointer.  No destination variable.
    // We return the full statement string; emit_stmt() will append ";\n".
    // -----------------------------------------------------------------------
    case RhsKind::STORE:
        return "*" + local_name(rhs.op1) + " = " + local_name(rhs.op2);

    // -----------------------------------------------------------------------
    // CALL: %dst = call Path(arg1, arg2, …)  →  Path_mangled(arg1, arg2, …)
    //
    // Path mangling: "::" → "_"
    // Arguments are the local names, comma-separated.
    // -----------------------------------------------------------------------
    case RhsKind::CALL: {
        std::string result = path_to_c(rhs.call_path) + "(";
        for (size_t i = 0; i < rhs.call_args.size(); ++i) {
            if (i > 0) result += ", ";
            result += local_name(rhs.call_args[i]);
        }
        result += ")";
        return result;
    }

    } // end switch
    return "/* unknown rhs */";
}

// =============================================================================
// emit_terminator() — emit the last instruction of a block
// =============================================================================
void CodeGen::emit_terminator(const Terminator& t) {
    switch (t.kind) {

    // -----------------------------------------------------------------------
    // JUMP: jump bb1  →  goto bb1;
    // Unconditional branch to another block.
    // -----------------------------------------------------------------------
    case TermKind::JUMP:
        out_ << "        goto " << t.label1 << ";\n";
        break;

    // -----------------------------------------------------------------------
    // CJUMP: cjump %cond, bb1, bb2  →  if (cond) goto bb1; else goto bb2;
    //
    // Both branches must be listed to ensure every code path is explicit.
    // GCC with -Wextra would warn about "control reaches end of non-void
    // function" if we omitted the else branch.
    // -----------------------------------------------------------------------
    case TermKind::CJUMP:
        out_ << "        if (" << local_name(t.cond) << ") "
             << "goto " << t.label1 << "; else goto " << t.label2 << ";\n";
        break;

    // -----------------------------------------------------------------------
    // RETURN: return [%val]  →  return val;  /  return;
    // -----------------------------------------------------------------------
    case TermKind::RETURN:
        if (t.has_ret_val) {
            out_ << "        return " << local_name(t.ret_local) << ";\n";
        } else {
            out_ << "        return;\n";
        }
        break;
    }
}

// =============================================================================
// type_to_c() — convert a ResIRType to its C type string
// =============================================================================
// Handles the full recursive case:
//   ptr<ptr<i32>>  builds up as:
//     type_to_c(ptr<i32>) + "*"
//     = (type_to_c(i32) + "*") + "*"
//     = "int32_t" + "*" + "*"
//     = "int32_t**"
std::string CodeGen::type_to_c(const ResIRType& t) const {
    switch (t.kind) {
        case TypeKind::BOOL:  return "bool";
        case TypeKind::I32:   return "int32_t";
        case TypeKind::I64:   return "int64_t";
        case TypeKind::U32:   return "uint32_t";
        case TypeKind::F64:   return "double";

        case TypeKind::PATH:
            // User-defined type: Custom::Struct::Point → Custom_Struct_Point
            return path_to_c(t.path);

        case TypeKind::PTR:
            // Recursive case: ptr<T> → (C type of T)*
            // Example:  ptr<i32>  →  "int32_t" + "*"  →  "int32_t*"
            if (t.inner) {
                return type_to_c(*t.inner) + "*";
            }
            return "void*"; // should never happen in a validated program
    }
    return "int32_t"; // unreachable, but satisfies -Wreturn-type
}

// =============================================================================
// path_to_c() — mangle a ResIR path to a valid C identifier
// =============================================================================
// C identifiers cannot contain "::".  We replace every occurrence of "::"
// with "_".  This is a one-way transformation (we never need to reverse it
// at this stage, since we only generate C, not link back to ResIR).
std::string CodeGen::path_to_c(const std::string& path) {
    std::string result = path;
    // Find and replace all occurrences of "::" with "_".
    // std::string::find returns the position of the first match, or npos if none.
    size_t pos = 0;
    while ((pos = result.find("::", pos)) != std::string::npos) {
        result.replace(pos, 2, "_");  // replace 2 chars ("::") with "_"
        pos += 1;                      // advance past the replacement
    }
    return result;
}

// =============================================================================
// local_name() — strip the "%" prefix (no-op here because the parser already
// stores locals without "%", but kept as a named helper for documentation)
// =============================================================================
std::string CodeGen::local_name(const std::string& name) {
    // The parser's parse_local() calls t.text.substr(1) to strip the leading
    // '%', so by the time a local name reaches the CFG it is already clean.
    // For example: "%a" in the source file → "a" in the CFG.
    return name;
}

// =============================================================================
// binop_str() — map BinOp enum → C operator token
// =============================================================================
std::string CodeGen::binop_str(BinOp op) {
    switch (op) {
        case BinOp::ADD: return "+";
        case BinOp::SUB: return "-";
        case BinOp::MUL: return "*";
        case BinOp::DIV: return "/";
        case BinOp::MOD: return "%";
        case BinOp::EQ:  return "==";
        case BinOp::NE:  return "!=";
        case BinOp::LT:  return "<";
        case BinOp::LE:  return "<=";
        case BinOp::GT:  return ">";
        case BinOp::GE:  return ">=";
        case BinOp::AND: return "&&";
        case BinOp::OR:  return "||";
    }
    return "+"; // unreachable
}

// =============================================================================
// unop_str() — map UnOp enum → C operator token
// =============================================================================
std::string CodeGen::unop_str(UnOp op) {
    switch (op) {
        case UnOp::NEG: return "-";  // arithmetic negation: -x
        case UnOp::NOT: return "!";  // logical not: !x
    }
    return "-"; // unreachable
}
